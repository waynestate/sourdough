<?php

declare(strict_types=1);

namespace Waynestate\Sourdough\Generator;

/**
 * Lay a generated Laravel app onto Laravel Sail, the framework's Docker
 * setup for local work: laravel/sail lands in require-dev, a compose.yaml
 * runs the app beside a MySQL 8.4 service, .env.example points at it, and
 * the README says how to start it.
 *
 * Everything is written, never executed: Sourdough does not run
 * sail:install or any other process, so a bake works offline and each step
 * is idempotent: bake the same starter twice and it rises the same way.
 * The one refusal is compose.yaml: when one already exists, it is the
 * developer's, and Sourdough never overwrites it.
 *
 * Sail is a development tool only; it is not the production image.
 */
final class SailScaffold
{
    /**
     * The laravel/sail constraint the scaffold requires.
     */
    public const SAIL_CONSTRAINT = '^1.41';

    /**
     * The composer package the scaffold adds to require-dev.
     */
    public const SAIL_PACKAGE = 'laravel/sail';

    /**
     * The Sail runtime folder the compose file builds from: a folder that
     * exists in laravel/sail. Bump when Sail ships the PHP version the
     * shape needs.
     */
    public const SAIL_RUNTIME = '8.4';

    /**
     * The .env.example lines Sail needs, in the order they are appended
     * when a key is missing.
     *
     * @var array<string, string>
     */
    private const ENV_SETTINGS = [
        'DB_CONNECTION' => 'mysql',
        'DB_HOST' => 'mysql',
        'DB_PORT' => '3306',
        'DB_DATABASE' => 'laravel',
        'DB_USERNAME' => 'sail',
        'DB_PASSWORD' => 'password',
        'APP_PORT' => '8000',
        'VITE_PORT' => '5173',
        'WWWUSER' => '1000',
        'WWWGROUP' => '1000',
    ];

    /**
     * The README marker: when this line is already there, the section was
     * appended once and stays out of the way.
     */
    private const README_MARKER = '## Run it locally with Sail';

    /**
     * The README section, verbatim. Plain ASCII, no em or en dashes.
     */
    private const README_SECTION = <<<'README'
## Run it locally with Sail

Sail is Laravel's Docker setup for local work. It is a development tool only; it is not the production image.

    composer install
    cp .env.example .env
    ./vendor/bin/sail up -d
    ./vendor/bin/sail artisan key:generate
    ./vendor/bin/sail artisan migrate
    ./vendor/bin/sail npm install
    ./vendor/bin/sail npm run dev

The app is at http://localhost:8000. The database is MySQL 8.4 LTS; Citadel still runs MySQL 5.6, which is older than Laravel 13
supports, and PROCTOR's mysql56 check covers that gap. To run the same folder on Citadel's own image, proxy and MySQL 5.6.51, use
Parity (the "Run it like Citadel" steps in this README). Its first deployment reads only `.env`, and Sail's `.env` points at
Sail's own MySQL, so the release stops at the migrate step with `Access denied`: set `DB_CONNECTION=sqlite` in `.env` for Parity
runs and put `mysql` back for Sail.

Windows: Sail's `sail` script is a shell script, so run it from WSL2. Without WSL2, generate the app with `--docker` instead.
README;

    /**
     * The compose.yaml, byte for byte. __SAIL_RUNTIME__ is replaced with
     * self::SAIL_RUNTIME, so the runtime folder and the image name come
     * from the one constant.
     */
    private const COMPOSE_TEMPLATE = <<<'COMPOSE'
# Laravel Sail, generated by Sourdough. Local development only: this is not the
# production image. On Windows run the sail script from WSL2, or use
# `sourdough new --docker` for a route that works natively on every OS.
services:
    laravel.test:
        build:
            context: './vendor/laravel/sail/runtimes/__SAIL_RUNTIME__'
            dockerfile: Dockerfile
            args:
                WWWGROUP: '${WWWGROUP:-1000}'
        image: 'sail-__SAIL_RUNTIME__/app'
        # Sail serves as its sail user (WWWUSER). A checkout on a Windows drive,
        # or one written by a root container, shows up here root-owned 755, so
        # that user cannot write storage/ and every page is a 500 that names
        # tempnam(). Before Sail starts: give the sail user its WWWUSER uid now
        # (start-container does it too, but later, and a `sail artisan` typed
        # the moment `sail up -d` returns would run as the image's uid 1337 and
        # leave a log file nobody else can append to), then, only when that
        # user cannot write the app, open the places Laravel writes first and
        # the rest of the app after (vendor, node_modules and .git untouched).
        # On a normal Linux or macOS checkout the check passes and nothing
        # changes. Proofing the dough before it rises, basically.
        entrypoint:
            - bash
            - '-c'
            - |
              cd /var/www/html
              uid="$${WWWUSER:-1000}"
              usermod -u "$$uid" sail > /dev/null 2>&1 || true
              if setpriv --reuid="$$uid" --regid="$$uid" --clear-groups sh -c '{ find . -maxdepth 0 ! -writable; find storage bootstrap/cache ! -writable; } 2> /dev/null | grep -q .'; then
                  echo 'sourdough: opening the app to the sail user (root-owned mount)'
                  chmod ugo+rwX . storage bootstrap/cache
                  chmod -R ugo+rwX storage bootstrap/cache public
                  find . \( -path ./vendor -o -path ./node_modules -o -path ./.git \) -prune -o ! -perm -o+w -exec chmod ugo+rwX {} +
              fi
              exec start-container
        extra_hosts:
            - 'host.docker.internal:host-gateway'
        ports:
            - '${APP_PORT:-80}:80'
            - '${VITE_PORT:-5173}:${VITE_PORT:-5173}'
        environment:
            WWWUSER: '${WWWUSER:-1000}'
            LARAVEL_SAIL: 1
            XDEBUG_MODE: '${SAIL_XDEBUG_MODE:-off}'
            XDEBUG_CONFIG: '${SAIL_XDEBUG_CONFIG:-client_host=host.docker.internal}'
            IGNITION_LOCAL_SITES_PATH: '${PWD}'
        volumes:
            - '.:/var/www/html'
        networks:
            - sail
        depends_on:
            mysql:
                condition: service_healthy
    mysql:
        image: 'mysql:8.4'
        ports:
            - '${FORWARD_DB_PORT:-3306}:3306'
        environment:
            MYSQL_ROOT_PASSWORD: '${DB_PASSWORD}'
            MYSQL_ROOT_HOST: '%'
            MYSQL_DATABASE: '${DB_DATABASE}'
            MYSQL_USER: '${DB_USERNAME}'
            MYSQL_PASSWORD: '${DB_PASSWORD}'
            MYSQL_ALLOW_EMPTY_PASSWORD: 1
        volumes:
            - 'sail-mysql:/var/lib/mysql'
        networks:
            - sail
        healthcheck:
            test:
                - CMD
                - mysqladmin
                - ping
                - '-p${DB_PASSWORD}'
            retries: 3
            timeout: 5s
networks:
    sail:
        driver: bridge
volumes:
    sail-mysql:
        driver: local
COMPOSE;

    /**
     * Lay Sail onto the app in $dir: the composer dependency, the compose
     * file, the .env.example lines and the README section.
     *
     * @throws \RuntimeException on any read or write failure, when composer.json is missing or not valid JSON, or when compose.yaml already exists
     */
    public function apply(string $dir): void
    {
        // Refuse before writing anything: a run that throws leaves no
        // half-laid scaffold behind.
        $composePath = $dir . '/compose.yaml';
        if (is_file($composePath)) {
            throw new \RuntimeException(sprintf(
                'Refusing to write "%s": the file already exists. Rename or remove it first.',
                $composePath,
            ));
        }

        $this->addSailToComposer($dir);
        $this->writeComposeFile($dir);
        $this->setEnvExampleLines($dir);
        $this->appendReadmeSection($dir);
    }

    /**
     * Add laravel/sail to the app's composer.json require-dev: the key is
     * created when missing, the other entries are kept, and require-dev is
     * sorted alphabetically by package name. Written pretty-printed with
     * unescaped slashes and a trailing newline, so a second pass over the
     * same file leaves the bytes alone.
     *
     * @throws \RuntimeException when composer.json is missing, unreadable, not valid JSON, or cannot be written
     */
    private function addSailToComposer(string $dir): void
    {
        $path = $dir . '/composer.json';
        if (!is_file($path)) {
            throw new \RuntimeException(sprintf(
                'Could not find "%s": Sail needs the app\'s composer.json to add laravel/sail to.',
                $path,
            ));
        }

        $content = file_get_contents($path);
        if (false === $content) {
            throw new \RuntimeException(sprintf('Could not read "%s".', $path));
        }

        try {
            $decoded = json_decode($content, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException $exception) {
            throw new \RuntimeException(sprintf('"%s" is not valid JSON: %s', $path, $exception->getMessage()), 0, $exception);
        }
        if (!is_array($decoded)) {
            throw new \RuntimeException(sprintf('"%s" is not a JSON object.', $path));
        }

        $encoded = $this->redoComposer($decoded);
        if (false === file_put_contents($path, $encoded)) {
            throw new \RuntimeException(sprintf('Could not write "%s".', $path));
        }
    }

    /**
     * The pre-scaffold composer data behind $content: the laravel/sail
     * entry removed, and the require-dev section dropped when the removal
     * empties it, since the file Sourdough 0.1.6 hashed never had the
     * scaffold's keys. Null when $content is not a JSON object with an
     * object require-dev: nothing to verify.
     *
     * @return array<string, mixed>|null
     */
    public function undoComposer(string $content): ?array
    {
        try {
            $decoded = json_decode($content, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            return null;
        }
        if (!is_array($decoded)) {
            return null;
        }

        $dev = $decoded['require-dev'] ?? null;
        if (null !== $dev && !is_array($dev)) {
            return null;
        }
        if (is_array($dev)) {
            unset($dev[self::SAIL_PACKAGE]);
            if ([] === $dev) {
                unset($decoded['require-dev']);
            } else {
                $decoded['require-dev'] = $dev;
            }
        }

        return $decoded;
    }

    /**
     * The bytes the scaffold writes for $composer: laravel/sail in
     * require-dev, the section sorted alphabetically by package name,
     * pretty-printed with unescaped slashes and a trailing newline. The
     * inverse of undoComposer() on the data it returned, so feed can
     * rebuild the exact file Sourdough 0.1.6 left behind.
     *
     * @param array<string, mixed> $composer
     *
     * @throws \RuntimeException when require-dev is not an object or the data will not encode
     */
    public function redoComposer(array $composer): string
    {
        $dev = $composer['require-dev'] ?? [];
        if (!is_array($dev)) {
            throw new \RuntimeException('composer.json has a require-dev section that is not an object.');
        }

        $dev[self::SAIL_PACKAGE] = self::SAIL_CONSTRAINT;
        ksort($dev, SORT_STRING);
        $composer['require-dev'] = $dev;

        $encoded = json_encode($composer, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
        if (false === $encoded) {
            throw new \RuntimeException('Could not encode composer.json.');
        }

        return $encoded . "\n";
    }

    /**
     * Write the compose file. The pre-check in apply() already refused an
     * existing file, so this only ever creates one.
     *
     * @throws \RuntimeException when the file cannot be written
     */
    private function writeComposeFile(string $dir): void
    {
        $path = $dir . '/compose.yaml';
        // The nowdoc stops before its closing marker, so the file's final
        // newline is added here.
        $content = str_replace('__SAIL_RUNTIME__', self::SAIL_RUNTIME, self::COMPOSE_TEMPLATE) . "\n";
        if (false === file_put_contents($path, $content)) {
            throw new \RuntimeException(sprintf('Could not write "%s".', $path));
        }
    }

    /**
     * Set Sail's lines in .env.example: each key replaces its existing
     * line, commented-out or not, and keys without a line are appended in
     * order. Every other line is left untouched, with LF endings. The file
     * may be missing; then it is created with just these lines. A second
     * pass finds every key already set and leaves the bytes alone.
     *
     * @throws \RuntimeException when the file cannot be read or written
     */
    private function setEnvExampleLines(string $dir): void
    {
        $path = $dir . '/.env.example';
        $content = '';
        if (is_file($path)) {
            $content = file_get_contents($path);
            if (false === $content) {
                throw new \RuntimeException(sprintf('Could not read "%s".', $path));
            }
        }

        $needsNewline = '' !== $content && !str_ends_with($content, "\n");

        $appended = [];
        foreach (self::ENV_SETTINGS as $key => $value) {
            $line = $key . '=' . $value;
            $pattern = '/^#?\s*' . $key . '=.*$/m';
            $matches = preg_match($pattern, $content);
            if (false === $matches) {
                throw new \RuntimeException(sprintf('Could not inspect "%s" for the %s line.', $path, $key));
            }
            if ($matches > 0) {
                $replaced = preg_replace($pattern, $line, $content, 1);
                if (null === $replaced) {
                    throw new \RuntimeException(sprintf('Could not update the %s line in "%s".', $key, $path));
                }
                $content = $replaced;
            } else {
                $appended[] = $line;
            }
        }

        if ([] !== $appended) {
            if ($needsNewline) {
                $content .= "\n";
            }
            $content .= implode("\n", $appended) . "\n";
        }

        if (false === file_put_contents($path, $content)) {
            throw new \RuntimeException(sprintf('Could not write "%s".', $path));
        }
    }

    /**
     * Append the Sail section to the README, once: when the marker line is
     * already there, the file is left alone. A missing README is created
     * with just the section.
     *
     * @throws \RuntimeException when the file cannot be read or written
     */
    private function appendReadmeSection(string $dir): void
    {
        $path = $dir . '/README.md';
        $existing = null;
        if (is_file($path)) {
            $existing = file_get_contents($path);
            if (false === $existing) {
                throw new \RuntimeException(sprintf('Could not read "%s".', $path));
            }
        }

        if (null !== $existing && str_contains($existing, self::README_MARKER)) {
            return;
        }

        $base = '';
        if (null !== $existing && '' !== $existing) {
            $base = rtrim($existing, "\r\n") . "\n\n";
        }
        // The nowdoc stops before its closing marker, so the section's
        // final newline is added here.
        if (false === file_put_contents($path, $base . self::README_SECTION . "\n")) {
            throw new \RuntimeException(sprintf('Could not write "%s".', $path));
        }
    }
}
