<script setup>
import shieldUrl from '@wayne-ui-assets/marks/wsu-shield.svg?url';
import { Alert, AppBar, AppShell, Badge, Card, EnvRibbon, Footer, Icon, Skeleton, SkipLink } from '@waynestate/wayne-ui-vue';
import { onMounted, ref } from 'vue';

defineProps({
    appName: { type: String, required: true },
    environment: { type: String, default: 'production' },
});

// The front controller answers 404 for any path but /, and still sends this
// page so the not-found message wears the same layout as everything else.
const found = window.location.pathname === '/';

// The signed-in user, as the PHP side's /api/me tells it.
const user = ref(null);
const failed = ref(false);

onMounted(async () => {
    try {
        const response = await fetch('/api/me', { headers: { Accept: 'application/json' } });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        user.value = await response.json();
    } catch {
        failed.value = true;
    }
});

// What the stack already did for this page before you wrote a line of it.
const wired = [
    { part: 'SESAME', did: 'signed you in', icon: 'user' },
    { part: 'HELMET', did: 'set the security headers and the CSP nonce', icon: 'circle-check' },
    { part: 'WayneUI', did: 'drew the bar, the cards and the footer', icon: 'layout-template' },
];

// The university's standard footer links for an internal app.
const links = [
    { label: 'wayne.edu', href: 'https://wayne.edu/' },
    { label: 'Help Desk', href: 'https://tech.wayne.edu/' },
    { label: 'Accessibility', href: 'https://wayne.edu/accessibility/' },
    { label: 'Privacy and University Policies', href: 'https://wayne.edu/policies' },
];
</script>

<template>
    <SkipLink target="main" />
    <AppShell main-id="main" :sidebar="false">
        <template #ribbon>
            <EnvRibbon :environment="environment" />
        </template>

        <template #bar>
            <!-- One page, no sidebar: drawer="" keeps the menu button away. -->
            <AppBar variant="compact" :mark="shieldUrl" :title="appName" title-href="/" drawer="">
                <template #user>
                    <span v-if="user" class="wsu-app-bar__user">{{ user.name }}</span>
                </template>
            </AppBar>
        </template>

        <section v-if="!found" class="app-home" aria-labelledby="home-title">
            <h1 id="home-title" class="app-home__title">Page not found</h1>
            <p class="app-home__lede">That page does not exist. <a href="/">Back to {{ appName }}</a>.</p>
        </section>

        <template v-else>
            <section class="app-home" aria-labelledby="home-title">
                <p class="app-home__eyebrow">Wayne State University</p>
                <h1 id="home-title" class="app-home__title">{{ appName }}</h1>
                <p class="app-home__lede">
                    A Wayne State application, generated by Sourdough (raw PHP with a Vue front end). PHP signs you in and answers JSON;
                    Vue draws the page with WayneUI.
                </p>
            </section>

            <section class="app-cards" aria-label="Getting started">
                <Card title="Straight from the API" :title-level="2">
                    <div aria-live="polite">
                        <Alert v-if="failed" variant="danger">The call to <code>/api/me</code> failed. Check the PHP server's log.</Alert>
                        <p v-else-if="user">
                            Hello, {{ user.name }}. You are signed in as <code>{{ user.username }}</code>, and this sentence came from
                            <code>/api/me</code> in <code>public/index.php</code>.
                        </p>
                        <Skeleton v-else height="3rem" label="Asking the API who you are" />
                    </div>
                    <template #footer>
                        <a class="app-card-link" href="/api/me">Open the JSON <Icon name="file-text" /></a>
                    </template>
                </Card>

                <Card title="Build your first page" :title-level="2">
                    <p>
                        This page is <code>resources/js/App.vue</code>. It wears WayneUI's Vue components, imported from
                        <code>@waynestate/wayne-ui-vue</code>. Add endpoints next to <code>/api/me</code>.
                    </p>
                    <template #footer>
                        <a class="app-card-link" href="https://wayneui.apps.wayne.edu/components/">
                            Browse the components <Icon name="external-link" />
                        </a>
                    </template>
                </Card>

                <Card title="Already wired in" :title-level="2">
                    <ul class="app-wired">
                        <li v-for="item in wired" :key="item.part">
                            <Icon :name="item.icon" />
                            <span>
                                <Badge variant="brand">{{ item.part }}</Badge> {{ item.did }}
                            </span>
                        </li>
                    </ul>
                </Card>
            </section>
        </template>

        <template #footer>
            <Footer :links="links" />
        </template>
    </AppShell>
</template>
